def knapsack_dynamic_programming(items, capacity):
    """
    Розв'язання задачі про рюкзак методом динамічного програмування
    
    items: список словників з ключами 'v' (цінність), 'w' (вага)
    capacity: максимальна місткість рюкзака
    
    Повертає: максимальну цінність, список обраних предметів, загальну вагу
    """
    n = len(items)
    
    # Створюємо таблицю dp[i][w] - максимальна цінність для i предметів та ваги w
    dp = [[0 for _ in range(capacity + 1)] for _ in range(n + 1)]
    
    # Заповнюємо таблицю
    for i in range(1, n + 1):
        for w in range(capacity + 1):
            item = items[i - 1]
            
            # Якщо предмет не поміщається
            if item['w'] > w:
                dp[i][w] = dp[i - 1][w]
            else:
                # Вибираємо максимум: взяти або не взяти предмет
                dp[i][w] = max(
                    dp[i - 1][w],  # не брати
                    dp[i - 1][w - item['w']] + item['v']  # взяти
                )
    
    # Відновлюємо список обраних предметів
    selected_items = []
    w = capacity
    
    for i in range(n, 0, -1):
        # Якщо цінність змінилася - предмет було взято
        if dp[i][w] != dp[i - 1][w]:
            selected_items.append(items[i - 1])
            w -= items[i - 1]['w']
    
    selected_items.reverse()
    
    # Обчислюємо загальну вагу
    total_weight = sum(item['w'] for item in selected_items)
    max_value = dp[n][capacity]
    
    return max_value, selected_items, total_weight

